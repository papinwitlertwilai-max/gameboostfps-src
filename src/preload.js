const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('boost', {
  isDesktop: true,
  run: (cmd) => ipcRenderer.invoke('run-cmd', cmd),
  runBatch: (cmds) => ipcRenderer.invoke('run-batch', cmds),
  getHwid: () => ipcRenderer.invoke('get-hwid'),
  licenseLoad: () => ipcRenderer.invoke('license-load'),
  licenseClear: () => ipcRenderer.invoke('license-clear'),
  licenseCall: (a) => ipcRenderer.invoke('license-call', a),
  sysinfo: () => ipcRenderer.invoke('sysinfo'),
  restorePoint: (name) => ipcRenderer.invoke('restore-point', name),
  hwStats: () => ipcRenderer.invoke('hwstats'),
  quickPing: (host) => ipcRenderer.invoke('quick-ping', host),
  listGames: () => ipcRenderer.invoke('list-games'),
  startupList: () => ipcRenderer.invoke('startup-list'),
  startupToggle: (item) => ipcRenderer.invoke('startup-toggle', item),
  powerPlanList: () => ipcRenderer.invoke('powerplan-list'),
  powerPlanDump: (guid) => ipcRenderer.invoke('powerplan-dump', guid),
  openPowerCfg: () => ipcRenderer.invoke('open-powercfg'),
  buildTrixiePlan: (o) => ipcRenderer.invoke('build-trixie-plan', o),
  gpuCaps: () => ipcRenderer.invoke('gpu-caps'),
  blocklistGet: () => ipcRenderer.invoke('blocklist-get'),
  supportBundle: (info) => ipcRenderer.invoke('support-bundle', info),
  osProfile: () => ipcRenderer.invoke('os-profile'),
  svcDisable: (a) => ipcRenderer.invoke('svc-disable', a),
  svcRestore: (a) => ipcRenderer.invoke('svc-restore', a),
  healthCheck: () => ipcRenderer.invoke('health-check'),
  isAdmin: () => ipcRenderer.invoke('is-admin'),
  timerRes: (on) => ipcRenderer.invoke('timer-res', on),
  dpcCheck: () => ipcRenderer.invoke('dpc-check'),
  onTrixieProgress: (cb) => ipcRenderer.on('trixie-progress', (_e, msg) => cb(msg)),
  overlayShow: () => ipcRenderer.invoke('overlay-show'),
  overlayHide: () => ipcRenderer.invoke('overlay-hide'),
  discordSet: (info) => ipcRenderer.invoke('discord-set', info)
})
